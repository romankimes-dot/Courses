// Deux en courses en même temps : chacun termine son panier
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const A = await (await b.newContext()).newPage(), B = await (await b.newContext()).newPage();
  const errs = []; [A, B].forEach(p => { p.on('pageerror', e => errs.push(e.message)); p.on('dialog', d => d.accept()); });
  const sync = async () => { for (const p of [A, B, A, B]) { await p.evaluate(() => Sync.run()); await p.waitForTimeout(150); } };
  await A.goto('http://localhost:8766/'); await A.fill('#welcomeName', 'Karim'); await A.click('[data-a=welcomeSolo]');
  await A.evaluate(() => { Sync.create('http://localhost:8766', 'anon'); }); await A.waitForTimeout(500);
  await B.goto(await A.evaluate(() => Sync.inviteLink())); await B.waitForFunction(() => S.items.length > 0);
  await B.fill('#meForm input', 'Julie'); await B.click('#meForm button');
  await A.click('[data-a=go][data-v=list]');
  await A.fill('#quick input', 'lait, pain, 2 kg tomates, pâtes, café, eau'); await A.press('#quick input', 'Enter');
  const tomates = await A.evaluate(() => { const i = findItem('tomates'); return `${i.name} | ${i.note}`; });
  await sync();
  await A.click('[data-a=goShopping]'); await B.click('[data-tab=list]'); await B.click('[data-a=goShopping]'); await sync();
  const banner = await A.textContent('.banner').catch(() => null);
  await A.click('[data-a=setWho][data-v="1"]'); await B.click('[data-a=setWho][data-v="2"]');
  const partA = await A.$$eval('main section:not(.basket) .row .name', e => e.map(x => x.textContent.trim().split(' ')[0]));
  const partB = await B.$$eval('main section:not(.basket) .row .name', e => e.map(x => x.textContent.trim().split(' ')[0]));
  await A.click(`main .row:has-text("${partA[0]}")`); await B.click(`main .row:has-text("${partB[0]}")`); await sync();
  await A.click('[data-a=finish]'); await A.fill('#finishForm input', '20'); await A.click('#finishForm .primary'); await sync();
  const afterA = await B.evaluate(() => ({ stillDone: S.items.filter(i => i.done).map(i => i.name), missing: S.items.filter(i => i.missing).length, trips: S.trips.map(t => t.names.join('+') + ' ' + t.total) }));
  await B.click('[data-a=finish]'); await B.fill('#finishForm input', '15'); await B.click('#finishForm .primary'); await sync();
  const final = await A.evaluate(() => S.trips.map(t => t.names.join('+') + ' ' + t.total));
  await A.fill('#quick input', 'lait'); await A.press('#quick input', 'Enter'); await A.waitForTimeout(50);
  await A.fill('#quick input', 'lait'); await A.press('#quick input', 'Enter'); await A.waitForTimeout(100);
  const dupToast = await A.textContent('#toast span');
  console.log(JSON.stringify({ tomates, banner, partA, partB, afterA, final, dupToast, errs }, null, 1));
  await b.close(); process.exit(0);
})();
